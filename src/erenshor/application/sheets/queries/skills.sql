SELECT
    skill_db_index,
    id,
    stable_key,
    s.display_name,
    skill_desc,
    type_of_skill,
    cooldown,
    c.display_name AS class_name,
    sc.required_level,
    require_behind,
    require_2h,
    require_dw,
    require_bow,
    require_shield,
    sim_players_autolearn,
    ae_skill,
    interrupt,
    spawn_on_use_stable_key,
    effect_to_apply_stable_key,
    affect_player,
    affect_target,
    skill_range,
    skill_power,
    percent_dmg,
    damage_type,
    scale_off_weapon,
    proc_weap,
    proc_shield,
    guarantee_proc,
    skill_can_crit,
    automate_attack,
    cast_on_target_stable_key,
    stance_to_use_stable_key,
    skill_anim_name,
    skill_icon_name,
    player_uses,
    npc_uses,
    s.resource_name
FROM skills s
LEFT JOIN skill_classes sc ON sc.skill_stable_key = s.stable_key
LEFT JOIN classes c ON c.class_name = sc.class_name
ORDER BY skill_db_index, c.display_name COLLATE NOCASE, sc.class_name;
