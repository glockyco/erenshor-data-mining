from __future__ import annotations

import pytest

from erenshor.application.wiki_lua.views import DataView, ViewDataError, ViewField, view_module_text

_VIEW = DataView(
    module="VendorStock",
    description="What each vendor sells.",
    entity="vendor",
    fields=(
        ViewField("item", "key", "The item."),
        ViewField("price", "integer", "Gold per item."),
        ViewField("type", "text", "The item's type."),
        ViewField("quest", "key", "The quest that adds the item.", optional=True),
    ),
)
_KNOWN = {"character:breena", "item:bread", "quest:flour"}


def _row(**overrides: object) -> dict[str, object]:
    return {"item": "item:bread", "price": 4, "type": "Consumable", **overrides}


def test_module_opens_with_its_field_declaration() -> None:
    text = view_module_text(_VIEW, {"character:breena": [_row(quest="quest:flour")]}, _KNOWN)

    assert text.splitlines()[:8] == [
        "-- Module:Erenshor/Data/VendorStock",
        "-- Generated by `erenshor wiki generate-lua`. The bot overwrites every edit of this page.",
        "-- What each vendor sells.",
        "-- Keys are vendor stable keys. Each maps to a list of rows with these fields:",
        "--   item (stable key): The item.",
        "--   price (integer): Gold per item.",
        "--   type (text): The item's type.",
        "--   quest (stable key, optional): The quest that adds the item.",
    ]
    assert text.splitlines()[8] == "return {"
    assert '["quest"] = "quest:flour",' in text


@pytest.mark.parametrize(
    ("row", "expected"),
    [
        (_row(item="item:gone"), "field 'item' holds 'item:gone', which is not in the link catalog"),
        (_row(type="[[Consumables]]"), "field 'type' holds wiki markup"),
        (_row(type="Consumable<br>"), "field 'type' holds wiki markup"),
        (_row(type="Consumable\nFood"), "field 'type' holds a line break"),
        (_row(price=True), "field 'price' must be integer, not bool"),
        (_row(price=4.5), "field 'price' must be integer, not float"),
        ({"item": "item:bread", "type": "Consumable"}, "field 'price' is missing"),
        (_row(sale=True), "field 'sale' is not declared"),
    ],
)
def test_rows_that_break_the_declaration_fail_naming_module_row_and_field(
    row: dict[str, object], expected: str
) -> None:
    with pytest.raises(ViewDataError) as error:
        view_module_text(_VIEW, {"character:breena": [_row(), row]}, _KNOWN)

    assert str(error.value).startswith("Module:Erenshor/Data/VendorStock: row 2 of character:breena: ")
    assert expected in str(error.value)


def test_an_entity_key_outside_the_link_catalog_fails() -> None:
    with pytest.raises(ViewDataError, match="vendor key 'character:gone' is not in the link catalog"):
        view_module_text(_VIEW, {"character:gone": [_row()]}, _KNOWN)


def test_a_key_list_checks_every_key() -> None:
    view = DataView("Classes", "Abilities.", "class", (ViewField("items", "keys", "Teaching items."),))

    with pytest.raises(ViewDataError, match="field 'items' holds 'item:gone'"):
        view_module_text(view, {"item:bread": [{"items": ["item:bread", "item:gone"]}]}, _KNOWN)
